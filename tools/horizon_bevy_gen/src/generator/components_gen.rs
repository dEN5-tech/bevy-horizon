use crate::ast::AstModule;

pub fn generate_components(modules: &[AstModule]) -> String {
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED BY horizon_bevy_gen. DO NOT EDIT DIRECTLY.\n");
    out.push_str("// First-class Bevy ECS Components derived from Horizon Native AST.\n\n");
    out.push_str("use bevy_ecs::prelude::*;\n\n");

    // Standard Horizon-to-Bevy Core Components
    out.push_str(r#"/// Unique Minecraft runtime entity ID
#[derive(Component, Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct MinecraftEntityId(pub u32);

/// Marker component for the local client player
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct LocalPlayer;

/// 3D World Position coordinates [x, y, z]
#[derive(Component, Debug, Clone, Copy, PartialEq)]
pub struct Position {
    pub x: f64,
    pub y: f64,
    pub z: f64,
}

impl Position {
    pub fn new(x: f64, y: f64, z: f64) -> Self {
        Self { x, y, z }
    }
    pub fn to_array(self) -> [f64; 3] {
        [self.x, self.y, self.z]
    }
    pub fn distance_to(&self, other: &Position) -> f64 {
        ((self.x - other.x).powi(2) + (self.y - other.y).powi(2) + (self.z - other.z).powi(2)).sqrt()
    }
}

/// Look rotation (yaw and pitch in degrees)
#[derive(Component, Debug, Clone, Copy, Default, PartialEq)]
pub struct Rotation {
    pub yaw: f32,
    pub pitch: f32,
}

/// 3D Movement velocity vector
#[derive(Component, Debug, Clone, Copy, Default, PartialEq)]
pub struct Velocity(pub [f64; 3]);

/// Entity current and maximum health points
#[derive(Component, Debug, Clone, Copy, PartialEq)]
pub struct Health {
    pub current: f32,
    pub max: f32,
}

/// Entity kind identifier (e.g. "minecraft:zombie")
#[derive(Component, Debug, Clone, PartialEq, Eq, Hash)]
pub struct EntityKind(pub String);

/// Marker for hostile monsters
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct HostileMob;

/// Marker for passive animals
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct PassiveAnimal;

/// Marker for undead creatures
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct Undead;

/// Dedicated typed mob markers (Codegen catalog)
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Zombie;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Skeleton;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Creeper;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Spider;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Enderman;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Cow;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Pig;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Sheep;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Chicken;
#[derive(Component, Debug, Default, Clone, Copy, PartialEq, Eq)] pub struct Villager;

"#);

    // Convert any custom structs discovered in AST modules into Components
    for module in modules {
        for s in &module.structs {
            if s.name == "Mob" || s.name == "Player" || s.name == "TransformStateComponent" {
                continue; // Covered by idiomatic components above
            }
            out.push_str(&format!("/// Discovered from AST: `{}`\n", s.name));
            out.push_str("#[derive(Component, Debug, Clone, PartialEq)]\n");
            out.push_str(&format!("pub struct {} {{\n", s.name));
            for f in &s.fields {
                out.push_str(&format!("    pub {}: {},\n", f.name, f.ty.raw));
            }
            out.push_str("}\n\n");
        }
    }

    // Bundles
    out.push_str(r#"/// Complete bundle for the local player entity in Bevy
#[derive(Bundle)]
pub struct LocalPlayerBundle {
    pub marker: LocalPlayer,
    pub pos: Position,
    pub rot: Rotation,
    pub health: Health,
}

/// Generic bundle for any Minecraft mob entity in Bevy
#[derive(Bundle)]
pub struct MinecraftMobBundle {
    pub id: MinecraftEntityId,
    pub kind: EntityKind,
    pub pos: Position,
    pub rot: Rotation,
    pub health: Health,
    pub vel: Velocity,
}
"#);

    out
}
