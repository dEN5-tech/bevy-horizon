use crate::ast::AstModule;

pub fn generate_events(modules: &[AstModule]) -> String {
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED BY horizon_bevy_gen. DO NOT EDIT DIRECTLY.\n");
    out.push_str("// First-class Bevy ECS Events mapped from Horizon Native hooks.\n\n");
    out.push_str("use bevy_ecs::prelude::*;\n\n");

    out.push_str(r#"/// Fired when player right-clicks an entity
#[derive(Event, Debug, Clone, PartialEq)]
pub struct EntityInteractEvent {
    pub entity_id: u32,
    pub kind: String,
    pub holding_item: bool,
    pub player_pos: [f64; 3],
}

/// Fired on keyboard button press or release
#[derive(Event, Debug, Clone, PartialEq, Eq)]
pub struct HorizonKeyEvent {
    pub key: String,
    pub pressed: bool,
    pub playing: bool,
}

/// Fired every frame when HUD is being rendered
#[derive(Event, Debug, Clone, Copy, PartialEq)]
pub struct HudDrawEvent {
    pub delta_seconds: f32,
}

/// Fired on client game tick
#[derive(Event, Debug, Clone, Copy, PartialEq)]
pub struct PlayerTickEvent {
    pub tick_number: u64,
}

/// Fired when an Options / Mod setting button is clicked
#[derive(Event, Debug, Clone, PartialEq, Eq)]
pub struct SettingClickEvent {
    pub mod_id: String,
    pub button_index: usize,
}

/// Fired when a chat message is received
#[derive(Event, Debug, Clone, PartialEq, Eq)]
pub struct ChatMessageReceivedEvent {
    pub message: String,
}
"#);

    // Scan parsed modules for additional hook functions
    for module in modules {
        for f in &module.functions {
            if f.is_native_hook {
                let event_name = to_event_name(&f.name);
                if event_name == "EntityInteractEvent"
                    || event_name == "KeyEvent"
                    || event_name == "HudDrawEvent"
                    || event_name == "PlayerTickEvent"
                    || event_name == "SettingClickEvent"
                    || event_name == "ChatMessageReceivedEvent"
                {
                    continue;
                }

                let mut fields = Vec::new();
                for p in &f.params {
                    if p.name == "self" || p.name == "game" || p.name == "batch" {
                        continue;
                    }
                    if let Some(owned_ty) = to_owned_event_type(&p.ty.raw) {
                        fields.push((p.name.clone(), owned_ty));
                    }
                }

                if !fields.is_empty() {
                    out.push_str(&format!("/// Hook event generated from `{}`\n", f.name));
                    out.push_str("#[derive(Event, Debug, Clone, PartialEq)]\n");
                    out.push_str(&format!("pub struct {} {{\n", event_name));
                    for (name, ty) in fields {
                        out.push_str(&format!("    pub {}: {},\n", name, ty));
                    }
                    out.push_str("}\n\n");
                }
            }
        }
    }

    out
}

fn to_owned_event_type(raw: &str) -> Option<String> {
    let raw = raw.trim();
    if raw.contains("Game") || raw.contains("HudBatch") || raw.contains("Corners") {
        return None;
    }
    if raw == "&str" || raw == "& str" {
        return Some("String".to_string());
    }
    if raw == "&mut bool" || raw == "& mut bool" {
        return Some("bool".to_string());
    }
    if raw.contains("ItemStack") {
        return Some("Option<String>".to_string());
    }
    if raw.starts_with("&mut ") || raw.starts_with("& mut ") {
        return None;
    }
    if raw.starts_with('&') {
        let stripped = raw.trim_start_matches('&').trim();
        return Some(stripped.to_string());
    }
    Some(raw.to_string())
}

fn to_event_name(fn_name: &str) -> String {
    let clean = fn_name.strip_prefix("native_").unwrap_or(fn_name);
    let parts: Vec<&str> = clean.split('_').collect();
    let mut name = parts
        .iter()
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect::<String>();
    if !name.ends_with("Event") {
        name.push_str("Event");
    }
    name
}
