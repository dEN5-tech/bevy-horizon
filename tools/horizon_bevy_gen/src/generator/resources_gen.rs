pub fn generate_resources() -> String {
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED BY horizon_bevy_gen. DO NOT EDIT DIRECTLY.\n");
    out.push_str("// First-class Bevy ECS Resources for Horizon client state & outbox commands.\n\n");
    out.push_str("use bevy_ecs::prelude::*;\n\n");

    out.push_str(r#"/// Global game tick and frame time tracking
#[derive(Resource, Debug, Default, Clone, Copy, PartialEq)]
pub struct HorizonClock {
    pub tick: u64,
    pub frame: u64,
    pub delta_seconds: f32,
}

/// Client HUD and menu state
#[derive(Resource, Debug, Default, Clone, PartialEq, Eq)]
pub struct ScreenState {
    pub in_menu: bool,
    pub playing: bool,
}

/// Drawing command buffer for HUD batching
#[derive(Resource, Debug, Default, Clone)]
pub struct HudDrawBuffer {
    pub rects: Vec<([f32; 4], u32)>,
    pub texts: Vec<(String, [f32; 2], u32, bool)>,
}

impl HudDrawBuffer {
    pub fn fill_rect(&mut self, rect: [f32; 4], argb: u32) {
        self.rects.push((rect, argb));
    }
    pub fn draw_text(&mut self, text: impl Into<String>, pos: [f32; 2], rgb: u32, shadow: bool) {
        self.texts.push((text.into(), pos, rgb, shadow));
    }
    pub fn clear(&mut self) {
        self.rects.clear();
        self.texts.clear();
    }
}

/// Outbox command queue: Systems push mutations here, Bridge executes them on Horizon `Game`
#[derive(Resource, Debug, Default, Clone)]
pub struct HorizonOutboxCommands {
    pub teleports: Vec<(u32, [f64; 3])>,
    pub impulses: Vec<(u32, [f64; 3])>,
    pub health_changes: Vec<(u32, f32)>,
    pub action_bars: Vec<String>,
    pub chat_messages: Vec<String>,
}

impl HorizonOutboxCommands {
    pub fn teleport_mob(&mut self, mob_id: u32, to_pos: [f64; 3]) {
        self.teleports.push((mob_id, to_pos));
    }
    pub fn push_mob(&mut self, mob_id: u32, velocity: [f64; 3]) {
        self.impulses.push((mob_id, velocity));
    }
    pub fn set_mob_health(&mut self, mob_id: u32, health: f32) {
        self.health_changes.push((mob_id, health));
    }
    pub fn send_action_bar(&mut self, text: impl Into<String>) {
        self.action_bars.push(text.into());
    }
    pub fn send_chat(&mut self, message: impl Into<String>) {
        self.chat_messages.push(message.into());
    }
    pub fn is_empty(&self) -> bool {
        self.teleports.is_empty()
            && self.impulses.is_empty()
            && self.health_changes.is_empty()
            && self.action_bars.is_empty()
            && self.chat_messages.is_empty()
    }
    pub fn clear(&mut self) {
        self.teleports.clear();
        self.impulses.clear();
        self.health_changes.clear();
        self.action_bars.clear();
        self.chat_messages.clear();
    }
}
"#);

    out
}
