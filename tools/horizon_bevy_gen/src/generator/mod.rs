use std::fs;
use std::path::Path;

pub mod bridge_gen;
pub mod components_gen;
pub mod events_gen;
pub mod resources_gen;

use crate::ast::AstModule;

pub struct GeneratedCrate {
    pub lib_rs: String,
    pub prelude_rs: String,
    pub components_rs: String,
    pub events_rs: String,
    pub resources_rs: String,
    pub bridge_rs: String,
}

pub fn generate_crate(modules: &[AstModule]) -> GeneratedCrate {
    let components_rs = components_gen::generate_components(modules);
    let events_rs = events_gen::generate_events(modules);
    let resources_rs = resources_gen::generate_resources();
    let bridge_rs = bridge_gen::generate_bridge();

    let lib_rs = r#"// AUTO-GENERATED BY horizon_bevy_gen. DO NOT EDIT DIRECTLY.
// First-Class Bevy ECS Runtime for Horizon Native Mods.

pub mod components;
pub mod events;
pub mod resources;
pub mod bridge;
pub mod prelude;

pub use bevy_ecs::prelude::*;
pub use components::*;
pub use events::*;
pub use resources::*;
pub use bridge::*;
"#
    .to_string();

    let prelude_rs = r#"// Convenience prelude for Horizon Bevy mods
pub use bevy_ecs::prelude::*;
pub use crate::components::*;
pub use crate::events::*;
pub use crate::resources::*;
pub use crate::bridge::*;
"#
    .to_string();

    GeneratedCrate {
        lib_rs,
        prelude_rs,
        components_rs,
        events_rs,
        resources_rs,
        bridge_rs,
    }
}

pub fn write_generated_crate(output_dir: &Path, generated: &GeneratedCrate) -> Result<(), String> {
    let src_dir = output_dir.join("src");
    fs::create_dir_all(&src_dir).map_err(|e| format!("Failed to create src dir: {e}"))?;

    let cargo_toml = r#"[package]
name = "bevy_horizon"
version = "0.1.0"
edition = "2024"
description = "First-class Bevy ECS types, events, components, and bridge for Minecraft Horizon"

[dependencies]
bevy_ecs = "0.20"
"#;

    fs::write(output_dir.join("Cargo.toml"), cargo_toml)
        .map_err(|e| format!("Failed to write Cargo.toml: {e}"))?;
    fs::write(src_dir.join("lib.rs"), &generated.lib_rs)
        .map_err(|e| format!("Failed to write lib.rs: {e}"))?;
    fs::write(src_dir.join("prelude.rs"), &generated.prelude_rs)
        .map_err(|e| format!("Failed to write prelude.rs: {e}"))?;
    fs::write(src_dir.join("components.rs"), &generated.components_rs)
        .map_err(|e| format!("Failed to write components.rs: {e}"))?;
    fs::write(src_dir.join("events.rs"), &generated.events_rs)
        .map_err(|e| format!("Failed to write events.rs: {e}"))?;
    fs::write(src_dir.join("resources.rs"), &generated.resources_rs)
        .map_err(|e| format!("Failed to write resources.rs: {e}"))?;
    fs::write(src_dir.join("bridge.rs"), &generated.bridge_rs)
        .map_err(|e| format!("Failed to write bridge.rs: {e}"))?;

    Ok(())
}
