pub fn generate_bridge() -> String {
    let mut out = String::new();
    out.push_str("// AUTO-GENERATED BY horizon_bevy_gen. DO NOT EDIT DIRECTLY.\n");
    out.push_str("// Bidirectional Sync Bridge between Minecraft Horizon Game and Bevy World.\n\n");
    out.push_str("use bevy_ecs::prelude::*;\n");
    out.push_str("use std::collections::HashMap;\n");
    out.push_str("use crate::components::*;\n");
    out.push_str("use crate::resources::*;\n\n");

    out.push_str(r#"/// Primary runtime coordinator bridging Horizon and Bevy ECS
pub struct HorizonBridge {
    pub world: World,
    pub schedule: Schedule,
    player_entity: Option<Entity>,
    mob_map: HashMap<u32, Entity>,
}

impl Default for HorizonBridge {
    fn default() -> Self {
        Self::new()
    }
}

impl HorizonBridge {
    pub fn new() -> Self {
        let mut world = World::new();

        // Initialize core resources
        world.insert_resource(HorizonClock::default());
        world.insert_resource(ScreenState::default());
        world.insert_resource(HudDrawBuffer::default());
        world.insert_resource(HorizonOutboxCommands::default());

        let schedule = Schedule::default();

        Self {
            world,
            schedule,
            player_entity: None,
            mob_map: HashMap::new(),
        }
    }

    /// Ingests player state from Horizon into Bevy World
    pub fn ingest_player(
        &mut self,
        pos: [f64; 3],
        yaw: f32,
        pitch: f32,
        hp: f32,
        max_hp: f32,
    ) -> Entity {
        if let Some(entity) = self.player_entity {
            if let Some(mut p) = self.world.get_mut::<Position>(entity) {
                p.x = pos[0];
                p.y = pos[1];
                p.z = pos[2];
            }
            if let Some(mut r) = self.world.get_mut::<Rotation>(entity) {
                r.yaw = yaw;
                r.pitch = pitch;
            }
            if let Some(mut h) = self.world.get_mut::<Health>(entity) {
                h.current = hp;
                h.max = max_hp;
            }
            entity
        } else {
            let entity = self
                .world
                .spawn(LocalPlayerBundle {
                    marker: LocalPlayer,
                    pos: Position::new(pos[0], pos[1], pos[2]),
                    rot: Rotation { yaw, pitch },
                    health: Health {
                        current: hp,
                        max: max_hp,
                    },
                })
                .id();
            self.player_entity = Some(entity);
            entity
        }
    }

    /// Ingests a slice of living mobs from Horizon into Bevy World (Upsert)
    pub fn ingest_mobs(
        &mut self,
        mobs: impl IntoIterator<Item = (u32, String, [f64; 3], f32, f32)>,
    ) {
        for (id, kind, pos, hp, max_hp) in mobs {
            if let Some(&entity) = self.mob_map.get(&id) {
                if let Some(mut p) = self.world.get_mut::<Position>(entity) {
                    p.x = pos[0];
                    p.y = pos[1];
                    p.z = pos[2];
                }
                if let Some(mut h) = self.world.get_mut::<Health>(entity) {
                    h.current = hp;
                    h.max = max_hp;
                }
            } else {
                let entity = self
                    .world
                    .spawn(MinecraftMobBundle {
                        id: MinecraftEntityId(id),
                        kind: EntityKind(kind.clone()),
                        pos: Position::new(pos[0], pos[1], pos[2]),
                        rot: Rotation::default(),
                        health: Health {
                            current: hp,
                            max: max_hp,
                        },
                        vel: Velocity::default(),
                    })
                    .id();

                // Attach archetype tags based on kind
                Self::classify_and_tag(&mut self.world, entity, &kind);
                self.mob_map.insert(id, entity);
            }
        }
    }

    fn classify_and_tag(world: &mut World, entity: Entity, kind: &str) {
        let short = kind.strip_prefix("minecraft:").unwrap_or(kind);
        let mut entity_mut = world.entity_mut(entity);

        match short {
            "zombie" | "zombie_villager" | "husk" | "drowned" => {
                entity_mut.insert((Zombie, Undead, HostileMob));
            }
            "skeleton" | "stray" | "wither_skeleton" => {
                entity_mut.insert((Skeleton, Undead, HostileMob));
            }
            "creeper" => {
                entity_mut.insert((Creeper, HostileMob));
            }
            "spider" | "cave_spider" => {
                entity_mut.insert((Spider, HostileMob));
            }
            "enderman" => {
                entity_mut.insert((Enderman, HostileMob));
            }
            "cow" | "mooshroom" => {
                entity_mut.insert((Cow, PassiveAnimal));
            }
            "pig" => {
                entity_mut.insert((Pig, PassiveAnimal));
            }
            "sheep" => {
                entity_mut.insert((Sheep, PassiveAnimal));
            }
            "chicken" => {
                entity_mut.insert((Chicken, PassiveAnimal));
            }
            "villager" => {
                entity_mut.insert(Villager);
            }
            _ => {}
        }
    }

    /// Dispatches an event into Bevy World via Observers/Triggers
    pub fn trigger_event<'a, E: Event<Trigger<'a>: Default>>(&mut self, event: E) {
        self.world.trigger(event);
    }

    /// Runs one simulation tick of the Bevy Schedule
    pub fn run_schedule(&mut self) {
        if let Some(mut clock) = self.world.get_resource_mut::<HorizonClock>() {
            clock.tick += 1;
        }
        self.schedule.run(&mut self.world);
    }

    /// Drains outbox commands to be applied to Horizon Game
    pub fn drain_commands(&mut self) -> HorizonOutboxCommands {
        if let Some(mut outbox) = self.world.get_resource_mut::<HorizonOutboxCommands>() {
            let drained = outbox.clone();
            outbox.clear();
            drained
        } else {
            HorizonOutboxCommands::default()
        }
    }

    /// Drains HUD draw commands to be rendered via HudBatch
    pub fn drain_hud(&mut self) -> HudDrawBuffer {
        if let Some(mut hud) = self.world.get_resource_mut::<HudDrawBuffer>() {
            let drained = hud.clone();
            hud.clear();
            drained
        } else {
            HudDrawBuffer::default()
        }
    }
}
"#);

    out
}
